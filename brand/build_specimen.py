#!/usr/bin/env python3
"""Generate brand/specimen.html from brand/tokens.json.

The page shows every scale, every semantic text/background pair in light and dark mode with its
measured WCAG contrast ratio, and the card-face font options. Run it after build_tokens.py.
Run: python3 brand/build_specimen.py
"""
import json
from pathlib import Path

HERE = Path(__file__).parent
T = json.loads((HERE / "tokens.json").read_text())
C = T["color"]
STEPS = ["50", "100", "200", "300", "400", "500", "600", "700", "800", "900", "950"]


def val(ref_or_hex):
    v = ref_or_hex
    while isinstance(v, str) and v.startswith("{"):
        node = T
        for k in v[1:-1].split("."):
            node = node[k]
        v = node["$value"]
    return v


def role(mode, path):
    node = C[mode]
    for k in path.split("."):
        node = node[k]
    return val(node["$value"])


def lum(h):
    out = []
    for i in (1, 3, 5):
        c = int(h[i:i + 2], 16) / 255
        out.append(c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4)
    return 0.2126 * out[0] + 0.7152 * out[1] + 0.0722 * out[2]


def ratio(a, b):
    la, lb = sorted((lum(a), lum(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


PAIRS = [  # (label, fg role, bg role, min ratio)
    ("Body text", "text.default", "bg.canvas", 4.5),
    ("Secondary text", "text.secondary", "bg.canvas", 4.5),
    ("Muted text (minimum)", "text.muted", "bg.surface", 4.5),
    ("Link", "text.link", "bg.surface", 4.5),
    ("Primary button", "text.on-brand", "action.primary.bg", 4.5),
    ("Button hover", "text.on-brand", "action.primary.hover", 4.5),
    ("Streak / XP", "text.on-accent", "accent.bg", 4.5),
    ("Correct", "status.success.fg", "status.success.bg", 4.5),
    ("Not quite", "status.danger.fg", "status.danger.bg", 4.5),
    ("Needs review", "status.warning.fg", "status.warning.bg", 4.5),
    ("Info", "status.info.fg", "status.info.bg", 4.5),
    ("Input border", "border.control", "bg.surface", 3.0),
    ("Focus ring", "border.focus", "bg.surface", 3.0),
]
DECKS = ["leaf", "marigold", "kram", "orchid"]
FONTS = [
    ("Noto Sans Thai Looped", "Learner (default)", "Looped, friendly"),
    ("Sarabun", "Classic", "Looped, the official-document look"),
    ("Anuphan", "Real-world", "Loopless, like signs, menus and the web"),
    ("Itim", "Handwriting", "Like class notes"),
]


def esc(s):
    return s.replace("&", "&amp;").replace("<", "&lt;")


def ramps():
    rows = []
    for name in ["leaf", "marigold", "neutral", "kram", "orchid", "lacquer", "ember"]:
        cells = []
        for s in STEPS:
            h = C[name][s]["$value"]
            fg = "#211f1b" if lum(h) > 0.25 else "#ffffff"
            cells.append(f'<div class="sw" style="background:{h};color:{fg}"><b>{s}</b><span>{h}</span></div>')
        rows.append(f'<div class="ramp"><div class="lbl">{name}</div>{"".join(cells)}</div>')
    return "\n".join(rows)


def pairs(mode):
    out = []
    for label, fg, bg, need in PAIRS:
        f, b = role(mode, fg), role(mode, bg)
        r = ratio(f, b)
        ok = "AA" if r >= need else "FAIL"
        if fg.startswith("border"):
            sample = f'<span style="display:inline-block;width:42px;height:22px;border-radius:8px;border:2px solid {f};vertical-align:middle"></span>'
        else:
            sample = f'<span style="color:{f};font-weight:600">Aa ใบไม้</span>'
        out.append(f'<div class="pair" style="background:{b}">{sample}<div class="pl" style="color:{role(mode, "text.default") if not bg.startswith("action") and not bg.startswith("accent") else f}">{label}<small>{r:.2f}:1 &middot; {ok} (needs {need}:1)</small></div></div>')
    return "\n".join(out)


def decks(mode):
    out = []
    for d in DECKS:
        bg, fg, m = (role(mode, f"deck.{d}.{k}") for k in ("bg", "fg", "meter"))
        out.append(f'<div class="deck" style="background:{bg};color:{fg}"><b>{d.title()}</b><small>{ratio(fg, bg):.2f}:1 text &middot; {ratio(m, bg):.2f}:1 meter</small><div class="meter"><i style="background:{m}"></i></div></div>')
    return "\n".join(out)


def page():
    light_canvas, dark_canvas = role("light", "bg.canvas"), role("dark", "bg.canvas")
    rule = role("light", "bg.rule")
    fonts = "\n".join(
        f'<div class="font"><div class="name">{esc(n)}<small>{esc(label)} &middot; {esc(note)}</small></div>'
        f'<div class="sample" style="font-family:\'{n}\'">บ ป ด ต ข ฃ ช ซ ผ ฝ<span class="s">ภาษาไทยไม่ยากอย่างที่คิด</span></div></div>'
        for n, label, note in FONTS)
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Baimai &middot; colour and type specimen</title>
<!-- Generated by brand/build_specimen.py from tokens.json. Do not edit by hand. -->
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=Anuphan:wght@400;600&family=Mitr:wght@500&family=Noto+Sans+Thai+Looped:wght@400;600&family=Sarabun:wght@400;600&family=Itim&display=swap" rel="stylesheet">
<style>
*{{box-sizing:border-box}}
body{{margin:0;font-family:Anuphan,system-ui,sans-serif;color:#33302b;background:{light_canvas};background-image:repeating-linear-gradient({light_canvas} 0 31px,{rule} 31px 32px)}}
main{{max-width:1100px;margin:0 auto;padding:36px 22px 80px}}
h1,h2{{font-family:Mitr,Anuphan,sans-serif;font-weight:500}}
h1{{font-size:30px;margin:0 0 4px;color:#005224}}
h2{{font-size:20px;margin:44px 0 8px}}
.lede{{color:#5d5952;max-width:72ch;margin:0}}
.ramp{{display:grid;grid-template-columns:90px repeat(11,1fr);gap:4px;margin:6px 0}}
.lbl{{font-size:13px;font-weight:600;align-self:center}}
.sw{{border-radius:8px;height:62px;padding:6px;font-size:11px;display:flex;flex-direction:column;justify-content:flex-end}}
@media(max-width:760px){{.sw span{{display:none}}.ramp{{grid-template-columns:64px repeat(11,1fr)}}}}
.modes{{display:grid;grid-template-columns:1fr 1fr;gap:16px}}
@media(max-width:860px){{.modes{{grid-template-columns:1fr}}}}
.mode{{border-radius:20px;padding:16px}}
.pairs{{display:grid;grid-template-columns:1fr 1fr;gap:8px}}
.pair{{border-radius:12px;padding:10px 12px;display:flex;gap:10px;align-items:center;box-shadow:inset 0 0 0 1px rgba(128,128,128,.25)}}
.pl{{font-size:13px}}.pl small{{display:block;font-size:11px;opacity:.85}}
.decks{{display:grid;grid-template-columns:1fr 1fr;gap:8px;margin-top:10px}}
.deck{{border-radius:16px;padding:10px 12px;font-size:13px}}
.deck b{{font-family:Mitr;font-weight:500;font-size:15px;display:block}}
.deck small{{font-size:11px}}
.meter{{height:6px;border-radius:9px;background:rgba(128,128,128,.2);margin-top:6px}}.meter i{{display:block;height:100%;width:60%;border-radius:9px}}
.font{{background:#fff;border-radius:14px;padding:14px 18px;display:grid;grid-template-columns:230px 1fr;gap:16px;align-items:center;margin-bottom:8px}}
@media(max-width:760px){{.font{{grid-template-columns:1fr}}}}
.name{{font-weight:600;font-size:14px}}.name small{{display:block;font-weight:400;color:#5d5952;font-size:12px}}
.sample{{font-size:32px;line-height:1.4}}.sample .s{{display:block;font-size:17px;color:#5d5952}}
</style>
</head>
<body>
<main>
<h1>Baimai &middot; ใบไม้</h1>
<p class="lede">The Garden palette. Every scale has 11 OKLCH steps. Contrast ratios on this page are calculated from tokens.json with the WCAG 2.2 formula when the page is generated.</p>
<h2>Scales</h2>
{ramps()}
<h2>Semantic pairs</h2>
<div class="modes">
<div class="mode" style="background:{light_canvas};box-shadow:inset 0 0 0 1px #dbd9d5"><p style="margin:0 0 8px;font-weight:600">Light</p><div class="pairs">{pairs("light")}</div><div class="decks">{decks("light")}</div></div>
<div class="mode" style="background:{dark_canvas};color:#eeecea"><p style="margin:0 0 8px;font-weight:600">Dark</p><div class="pairs">{pairs("dark")}</div><div class="decks">{decks("dark")}</div></div>
</div>
<h2>Thai card-face font (user setting)</h2>
{fonts}
</main>
</body>
</html>
"""


if __name__ == "__main__":
    html = page()
    (HERE / "specimen.html").write_text(html)
    fails = html.count("FAIL (")
    print(f"wrote specimen.html ({fails} failing pairs)")
